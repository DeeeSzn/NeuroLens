"""Export service — generates summary reports from analysis results."""

from __future__ import annotations

from app.services.brain_regions import REGION_MODALITIES, REGION_ORDER


def generate_text_report(result: dict, job_id: str, filename: str, media_type: str = "video") -> str:
    """Generate a plain-text / markdown summary report."""
    lines: list[str] = []
    lines.append(f"# NeuroLens Analysis Report")
    lines.append(f"**File:** {filename}")
    lines.append(f"**Duration:** {result['duration_sec']}s")
    lines.append(f"**Timesteps:** {result['n_timesteps']} (TR = {result['tr_seconds']}s)")
    lines.append("**Evidence:** predicted average-subject cortical response; exploratory, not clinical or outcome-validated.")
    lines.append(f"**Reference:** {result.get('insight_reference_version') or 'unavailable'}")
    lines.append(f"**Ruleset:** {result.get('insight_ruleset_version') or 'unavailable'}")
    lines.append("**Scale:** within-clip normalized predictions, not measured BOLD or calibrated engagement.")
    lines.append("")

    # Region activation summary
    lines.append("## Average Region Activation")
    lines.append("")
    for r in REGION_ORDER:
        if media_type == "audio" and REGION_MODALITIES[r] == ["video"]:
            continue
        # .get guards legacy results saved before the named regions existed
        values = [t["regions"].get(r, 0.0) for t in result["timesteps"]]
        avg = sum(values) / len(values) if values else 0
        peak = max(values) if values else 0
        peak_t = result["timesteps"][values.index(peak)]["time_sec"] if values else 0
        label = "Prefrontal areas" if r == "mpfc_valuation" else r.replace("_", " ").capitalize()
        lines.append(
            f"- **{label}**: avg {avg:.3f}, peak {peak:.3f} at {peak_t:.1f}s"
        )

    lines.append("")

    insights = result.get("insights", [])
    lines.append("## Predicted Response Findings")
    if insights:
        lines.append("")
        for ins in insights:
            lines.append(f"- {ins['time_start']}–{ins['time_end']}s: {ins['description']} (z={ins['z']:+.2f}; {ins['reference']['n_clips']} other clips)")
    else:
        lines.append("No sustained benchmarked findings (or no compatible reference).")

    lines.append("")
    lines.append("---")
    lines.append("*Generated by NeuroLens — Powered by TRIBE v2*")

    return "\n".join(lines)


def generate_json_export(result: dict, job_id: str) -> dict:
    """Generate a clean JSON export (without raw vertices for smaller size)."""
    export = {
        "job_id": job_id,
        "duration_sec": result["duration_sec"],
        "n_timesteps": result["n_timesteps"],
        "tr_seconds": result["tr_seconds"],
        "timesteps": result["timesteps"],
        "insights": result.get("insights", []),
        "insight_reference_version": result.get("insight_reference_version"),
        "insight_ruleset_version": result.get("insight_ruleset_version"),
    }
    return export
